import assert from 'node:assert/strict';
import { mkdtempSync, writeFileSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
import { describe, it } from 'node:test';
import { env, loadEnvFile } from '../src/config.js';

// spec 021: the app's .env is loaded at start, never replacing a variable the process has
describe('the .env of the app', () => {
  it('fills only what the process lacks', () => {
    const dir = mkdtempSync(join(tmpdir(), 'synapsis-env-'));
    const file = join(dir, '.env');
    writeFileSync(file, '# Generated by NuclearLang\nSYN_PLAIN=tasks.sqlite\nSYN_QUOTED="two\\nlines \\"q\\" \\\\ \\$HOME"\nSYN_KEPT=from-file\n');
    process.env.SYN_KEPT = 'from-process';
    loadEnvFile(file);
    assert.equal(env('SYN_PLAIN'), 'tasks.sqlite');
    assert.equal(env('SYN_QUOTED'), 'two\nlines "q" \\ $HOME');
    assert.equal(env('SYN_KEPT'), 'from-process');
    assert.equal(env('SYN_NONE', 'default'), 'default');
    loadEnvFile(join(dir, 'missing.env'));
    for (const name of ['SYN_PLAIN', 'SYN_QUOTED', 'SYN_KEPT']) delete process.env[name];
  });
});
